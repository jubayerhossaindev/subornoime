#!/usr/bin/env python3
"""Generate fully regular Bangla clitic forms from the noun entries.

Clitics (টা/টি/টায়/গুলো/গুলি/গুলোর) attach to EVERY Bangla noun without
sandhi changes, so these forms are grammar-guaranteed real words people type
daily. The locative/possessive (এ/এর) attach without sandhi only to
consonant-final nouns — those are generated too, gated on the final sound.

Output: data/wordlist/15_clitic_forms.tsv (marked as generated; the seed
generator merges it like any other module).
"""
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORDLIST_DIR = ROOT / "data" / "wordlist"
OUT = WORDLIST_DIR / "15_clitic_forms.tsv"

VOWEL_SIGNS = set("ািীুূৃেৈোৌ")   # vowel diacritics that follow a consonant
HASANTA = "\u09cd"
JOINS = {"\u200c", "\u200d"}

def is_consonant_final(word: str) -> bool:
    """True when the word ends in a consonant sound (safe for এ/এর)."""
    for ch in reversed(word):
        if ch in JOINS:
            continue
        if ch == HASANTA:
            return True
        if ch in VOWEL_SIGNS:
            return False
        code = ord(ch)
        if 0x0980 <= code <= 0x09FF:
            # Full Bengali vowel letters (অ আ ই ঈ ...) end in a vowel sound.
            if code in (0x0985, 0x0986, 0x0987, 0x0988, 0x0989, 0x098A,
                        0x098B, 0x098F, 0x0990, 0x0993, 0x0994, 0x0995):
                return False
            return True
        return False
    return False

def main() -> int:
    nouns = []
    for path in sorted(WORDLIST_DIR.glob("*.tsv")):
        if path.name in ("relations.tsv", OUT.name):
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            fields = [f.strip() for f in line.split("\t")]
            word = unicodedata.normalize("NFC", fields[0])
            freq = int(fields[1]) if len(fields) > 1 else 1
            category = fields[2] if len(fields) > 2 else "noun"
            if category == "noun" and len(word) <= 20:
                nouns.append((word, freq))

    lines = [
        "# GENERATED by scripts/generate_clitics.py — regular Bangla clitic",
        "# forms of the noun entries (টা/টি/টায়/গুলো/গুলি/গুলোর + consonant-",
        "# final এ/এর). Do not edit by hand; edit the base noun modules and",
        "# regenerate.",
    ]
    seen = set()
    for word, freq in nouns:
        base = max(150, min(freq // 4, 600))
        forms = [
            (word + "টা", base),
            (word + "টি", base),
            (word + "টায়", base // 2),
            (word + "গুলো", base),
            (word + "গুলি", base // 2),
            (word + "গুলোর", base // 2),
        ]
        if is_consonant_final(word):
            forms.append((word + "ে", base))
            forms.append((word + "ের", base))
        for form, weight in forms:
            if form not in seen:
                seen.add(form)
                lines.append(f"{form}\t{weight}\tnoun\tcholito")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(seen)} forms from {len(nouns)} nouns")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
